/** Snippet body for an environment (content placed between begin and end). */
export function environmentBody(env: string): string {
  if (['itemize', 'enumerate'].includes(env)) return '\t\\item #{}';
  if (env === 'description') return '\t\\item[#{term}] #{}';
  if (env === 'figure' || env === 'figure*') {
    return '\t\\centering\n\t\\includegraphics[width=\\linewidth]{#{file}}\n\t\\caption{#{caption}}\n\t\\label{fig:#{label}}';
  }
  if (env === 'table' || env === 'table*') {
    return '\t\\centering\n\t\\begin{tabular}{#{lll}}\n\t\t#{}\n\t\\end{tabular}\n\t\\caption{#{caption}}\n\t\\label{tab:#{label}}';
  }
  if (env === 'tabular') return '\t#{}';
  return '\t#{}';
}

