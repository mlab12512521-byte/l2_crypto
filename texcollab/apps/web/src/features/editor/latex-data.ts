/**
 * Curated LaTeX vocabulary for autocompletion. Snippet syntax follows
 * @codemirror/autocomplete: #{name} marks a tab stop.
 */

export interface CommandSpec {
  /** Command name without backslash. */
  name: string;
  /** Snippet inserted after the backslash; defaults to the name. */
  snippet?: string;
  detail?: string;
}

const arg = (name: string, detail?: string, argName = ''): CommandSpec => ({
  name,
  snippet: `${name}{#{${argName}}}`,
  ...(detail ? { detail } : {}),
});
const plain = (name: string, detail?: string): CommandSpec => ({ name, ...(detail ? { detail } : {}) });

